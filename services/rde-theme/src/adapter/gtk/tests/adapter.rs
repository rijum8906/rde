#[test]
fn supersedes_only_older_generations_of_the_same_theme() {
    let temp = tempfile::tempdir().unwrap();
    let config_home = temp.path().join("config");
    let cache_dir = temp.path().join("cache");
    let gtk3_dir = cache_dir.join("gtk-3.0");
    for generation in ["rde-gtk-m3-v1", "rde-gtk-m3-v2", "Adwaita"] {
        std::fs::create_dir_all(gtk3_dir.join(generation)).unwrap();
        std::fs::write(gtk3_dir.join(generation).join("gtk.css"), "stale").unwrap();
    }

    let mut emitter = GtkEmitter::with_targets(config_home, cache_dir.clone(), true, false);
    emitter.set_unique_theme_name("rde-gtk-m3-v3".to_string());
    let output = emitter.render(&theme()).unwrap();

    let expected = vec![
        gtk3_dir.join("rde-gtk-m3-v1").join("gtk.css"),
        gtk3_dir.join("rde-gtk-m3-v2").join("gtk.css"),
    ];
    for path in expected {
        assert!(output.removals.contains(&path), "{:?}", output.removals);
    }
    assert!(
        !output
            .removals
            .contains(&gtk3_dir.join("rde-gtk-m3-v3").join("gtk.css")),
        "{:?}",
        output.removals
    );
    assert!(
        !output
            .removals
            .contains(&gtk3_dir.join("Adwaita").join("gtk.css")),
        "{:?}",
        output.removals
    );
}

#[test]
fn skips_tools_that_are_not_installed() {
    let temp = tempfile::tempdir().unwrap();
    let config_home = temp.path().join("config");
    let cache_dir = temp.path().join("cache");
    let mut emitter = GtkEmitter::with_targets(config_home.clone(), cache_dir.clone(), false, true);
    emitter.set_unique_theme_name("rde-gtk-m3-v3".to_string());

    let output = emitter.render(&theme()).unwrap();
    let paths: Vec<_> = output.files.iter().map(|(path, _)| path.clone()).collect();

    assert_eq!(paths.len(), 2, "{paths:?}");
    assert!(
        paths
            .iter()
            .all(|path| path.starts_with(cache_dir.join("gtk-4.0"))
                || path.starts_with(config_home.join("gtk-4.0"))),
        "{paths:?}"
    );
}
