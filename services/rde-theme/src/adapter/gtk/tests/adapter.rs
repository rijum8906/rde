//! # GTK Adapter Behavior Tests
//!
//! Covers the publication shape: one versioned CSS per GTK major version, the
//! `settings.ini` merge, the `GTK_THEME` export, and superseded generations.

use super::super::{GTK_ADAPTER_NAME, GtkEmitter};
use super::{theme, theme_with_variant};
use crate::adapter::Adapter;

#[test]
fn adapter_reports_its_registry_name() {
    let temp = tempfile::tempdir().unwrap();
    let emitter = GtkEmitter::with_targets(
        temp.path().to_path_buf(),
        temp.path().to_path_buf(),
        true,
        true,
    );
    assert_eq!(emitter.name(), GTK_ADAPTER_NAME);
}

#[test]
fn writes_versioned_css_and_settings_for_every_installed_tool() {
    let temp = tempfile::tempdir().unwrap();
    let config_home = temp.path().join("config");
    let cache_dir = temp.path().join("cache");
    let mut emitter = GtkEmitter::with_targets(config_home.clone(), cache_dir.clone(), true, true);
    emitter.set_unique_theme_name("rde-gtk-m3-v4".to_string());

    let output = emitter.render(&theme()).unwrap();
    let paths: Vec<_> = output.files.iter().map(|(path, _)| path.clone()).collect();

    for tool in ["gtk-3.0", "gtk-4.0"] {
        let css = cache_dir.join(tool).join("rde-gtk-m3-v4").join("gtk.css");
        let settings = config_home.join(tool).join("settings.ini");
        assert!(paths.contains(&css), "{paths:?}");
        assert!(paths.contains(&settings), "{paths:?}");

        let content = output
            .files
            .iter()
            .find(|(path, _)| path == &css)
            .map(|(_, bytes)| String::from_utf8_lossy(bytes).into_owned())
            .unwrap();
        assert!(
            content.starts_with("/* Generated by rde-theme; do not edit. */"),
            "{content}"
        );
    }
}

#[test]
fn settings_merge_preserves_unrelated_keys_and_sets_appearance() {
    let temp = tempfile::tempdir().unwrap();
    let config_home = temp.path().join("config");
    let cache_dir = temp.path().join("cache");
    let tool_dir = config_home.join("gtk-3.0");
    std::fs::create_dir_all(&tool_dir).unwrap();
    std::fs::write(
        tool_dir.join("settings.ini"),
        "; my gtk settings\n[Settings]\ngtk-font-name=Cantarell 11\n\
         gtk-theme-name=Adwaita\ngtk-application-prefer-dark-theme=false\n\
         gtk-cursor-theme-name=Adwaita\n\n[Other]\nkey=value\n",
    )
    .unwrap();

    let mut emitter = GtkEmitter::with_targets(config_home.clone(), cache_dir, true, false);
    emitter.set_unique_theme_name("rde-gtk-m3-v4".to_string());
    let output = emitter.render(&theme()).unwrap();
    for (path, bytes) in &output.files {
        crate::fs::write_atomic(path, bytes).unwrap();
    }

    let settings = std::fs::read_to_string(tool_dir.join("settings.ini")).unwrap();
    assert!(settings.contains("[Settings]"), "{settings}");
    assert!(
        settings.contains("gtk-font-name=Cantarell 11"),
        "{settings}"
    );
    assert!(
        settings.contains("gtk-cursor-theme-name=Adwaita"),
        "{settings}"
    );
    assert!(settings.contains("[Other]"), "{settings}");
    assert!(settings.contains("key=value"), "{settings}");
    assert!(
        settings.contains("gtk-theme-name=rde-gtk-m3-v4"),
        "{settings}"
    );
    assert!(
        settings.contains("gtk-application-prefer-dark-theme=true"),
        "{settings}"
    );
}

