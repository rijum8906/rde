//! # GTK CSS Coverage Tests
//!
//! Pins the header, the `@define-color` format, and the documented role order
//! so a new Material role cannot silently drop out of the stylesheet.

use super::roles;
use crate::adapter::gtk::render_gtk_css;

/// Every Material role the stylesheet must define, in documented order.
const ROLE_ORDER: [&str; 34] = [
    "primary",
    "on_primary",
    "primary_container",
    "on_primary_container",
    "secondary",
    "on_secondary",
    "secondary_container",
    "on_secondary_container",
    "tertiary",
    "on_tertiary",
    "tertiary_container",
    "on_tertiary_container",
    "error",
    "on_error",
    "error_container",
    "on_error_container",
    "background",
    "on_background",
    "surface",
    "on_surface",
    "surface_variant",
    "on_surface_variant",
    "surface_container_lowest",
    "surface_container_low",
    "surface_container",
    "surface_container_high",
    "surface_container_highest",
    "outline",
    "outline_variant",
    "shadow",
    "scrim",
    "inverse_surface",
    "inverse_on_surface",
    "inverse_primary",
];

#[test]
fn emits_one_define_color_per_role_in_documented_order() {
    let css = render_gtk_css(&roles());

    // The file starts with the generated-code header, exactly as GTK expects.
    assert!(
        css.starts_with("/* Generated by rde-theme; do not edit. */\n"),
        "{css}"
    );

    let definitions: Vec<&str> = css
        .lines()
        .filter(|line| line.starts_with("@define-color "))
        .collect();

    assert_eq!(definitions.len(), ROLE_ORDER.len(), "{css}");

    for (line, role) in definitions.iter().zip(ROLE_ORDER) {
        assert!(
            line.starts_with(&format!("@define-color {role} #")),
            "expected {role}, got {line}"
        );
        assert!(line.ends_with(';'), "{line}");
    }

    // `inverse_primary` is part of the fixed Material role set.
    assert!(css.contains("@define-color inverse_primary #"), "{css}");
}
