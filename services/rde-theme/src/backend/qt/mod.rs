//! # Qt and KDE Theme Integration
//!
//! Generates `kdeglobals` color fragments from semantic [`ColorRoles`].

use crate::{
    backend::{Backend, BackendError, BackendOutput},
    domain::resolved::{Color, ColorRoles, ResolvedTheme},
};
use std::path::PathBuf;

/// Formats a [`Color`] into decimal RGB `r,g,b` for KDE configurations.
fn to_kde_rgb(color: &Color) -> String {
    let clean = color.as_str().trim_start_matches('#');
    if let Ok(val) = u32::from_str_radix(clean, 16) {
        let r = (val >> 16) & 0xFF;
        let g = (val >> 8) & 0xFF;
        let b = val & 0xFF;
        format!("{r},{g},{b}")
    } else {
        "0,0,0".to_string()
    }
}

/// Generates a `kdeglobals` `[Colors:*]` INI fragment from [`ColorRoles`].
#[must_use]
pub fn render_kdeglobals(colors: &ColorRoles) -> String {
    let mut out = String::from("; Generated by rde-theme; do not edit.\n");

    let surface = to_kde_rgb(&colors.surface);
    let on_surface = to_kde_rgb(&colors.on_surface);
    let primary = to_kde_rgb(&colors.primary);
    let on_primary = to_kde_rgb(&colors.on_primary);
    let surface_container = to_kde_rgb(&colors.surface_container);
    let surface_container_highest = to_kde_rgb(&colors.surface_container_highest);

    // [Colors:Window]
    out.push_str("\n[Colors:Window]\n");
    out.push_str(&format!("BackgroundNormal={surface}\n"));
    out.push_str(&format!("ForegroundNormal={on_surface}\n"));

    // [Colors:View]
    out.push_str("\n[Colors:View]\n");
    out.push_str(&format!("BackgroundNormal={surface}\n"));
    out.push_str(&format!("ForegroundNormal={on_surface}\n"));

    // [Colors:Button]
    out.push_str("\n[Colors:Button]\n");
    out.push_str(&format!("BackgroundNormal={surface_container}\n"));
    out.push_str(&format!("ForegroundNormal={on_surface}\n"));

    // [Colors:Selection]
    out.push_str("\n[Colors:Selection]\n");
    out.push_str(&format!("BackgroundNormal={primary}\n"));
    out.push_str(&format!("ForegroundNormal={on_primary}\n"));

    // [Colors:Tooltip]
    out.push_str("\n[Colors:Tooltip]\n");
    out.push_str(&format!("BackgroundNormal={surface_container_highest}\n"));
    out.push_str(&format!("ForegroundNormal={on_surface}\n"));

    out
}

/// Backend adapter emitting Qt and KDE color schemes.
#[derive(Debug, Clone)]
pub struct QtEmitter {
    config_dir: PathBuf,
}

impl QtEmitter {
    /// Constructs a new [`QtEmitter`] targeting the user's config directory.
    #[must_use]
    pub fn new(config_dir: PathBuf) -> Self {
        Self { config_dir }
    }
}

impl Backend for QtEmitter {
    fn name(&self) -> &'static str {
        "qt"
    }

    fn render(&self, theme: &ResolvedTheme) -> Result<BackendOutput, BackendError> {
        let content = render_kdeglobals(&theme.colors);
        let target_file = self.config_dir.join("kdeglobals");

        Ok(BackendOutput {
            files: vec![(target_file, content.into_bytes())],
            env: Vec::new(),
        })
    }
}
