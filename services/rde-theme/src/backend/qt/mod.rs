/// Name of the color scheme generated by the service.
///
/// Used as the file stem for the generated schemes and as the
/// `ColorScheme` value in KDE configuration.
pub const QT_COLOR_SCHEME_NAME: &str = "RdeM3";

/// File name of the KDE color scheme below `color-schemes/`.
const KDE_COLOR_SCHEME_FILE_NAME: &str = "RdeM3.colors";

/// User color scheme directory below the XDG data home.
const KDE_COLOR_SCHEMES_SUBDIR: &str = "color-schemes";

/// KDE configuration file holding the active color groups.
const KDE_GLOBALS_FILE_NAME: &str = "kdeglobals";

/// File name of the qt5ct/qt6ct color scheme below `colors/`.
const QT_SCHEME_FILE_NAME: &str = "RdeM3.conf";

/// qt5ct configuration directory below the XDG config home.
const QT5CT_DIR: &str = "qt5ct";

/// qt6ct configuration directory below the XDG config home.
const QT6CT_DIR: &str = "qt6ct";

/// Subdirectory holding qt5ct/qt6ct color schemes.
const QT_COLORS_SUBDIR: &str = "colors";

/// qt5ct configuration file name.
const QT5CT_CONFIG_FILE: &str = "qt5ct.conf";

/// qt6ct configuration file name.
const QT6CT_CONFIG_FILE: &str = "qt6ct.conf";

/// Locations of the Qt and KDE configuration files the service maintains.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QtPaths {
    /// XDG configuration home (`$XDG_CONFIG_HOME` or `~/.config`).
    config_home: PathBuf,

    /// XDG data home (`$XDG_DATA_HOME` or `~/.local/share`).
    data_home: PathBuf,
}

impl QtPaths {
    /// Resolves the Qt configuration locations from the environment.
    ///
    /// # Errors
    /// Returns [`rde_core::errors::RdeError::NotFound`] when neither
    /// `XDG_CONFIG_HOME`/`XDG_DATA_HOME` nor `HOME` is available.
    pub fn resolve() -> RdeResult<Self> {
        Ok(Self {
            config_home: xdg_config_home()?,
            data_home: xdg_data_home()?,
        })
    }

    /// Builds the locations from explicit XDG homes, used by tests.
    pub fn from_homes(config_home: impl Into<PathBuf>, data_home: impl Into<PathBuf>) -> Self {
        Self {
            config_home: config_home.into(),
            data_home: data_home.into(),
        }
    }

    /// Returns the XDG configuration home.
    pub fn config_home(&self) -> &Path {
        &self.config_home
    }

    /// Returns the XDG data home.
    pub fn data_home(&self) -> &Path {
        &self.data_home
    }

    /// Returns the path of the standalone KDE color scheme.
    pub fn kde_color_scheme_file(&self) -> PathBuf {
        self.data_home
            .join(KDE_COLOR_SCHEMES_SUBDIR)
            .join(KDE_COLOR_SCHEME_FILE_NAME)
    }

    /// Returns the path of the user's `kdeglobals`.
    pub fn kde_globals_file(&self) -> PathBuf {
        self.config_home.join(KDE_GLOBALS_FILE_NAME)
    }

    /// Returns the path of the qt5ct color scheme.
    pub fn qt5ct_scheme_file(&self) -> PathBuf {
        self.qtct_dir(QT5CT_DIR).join(QT_SCHEME_FILE_NAME)
    }

    /// Returns the path of the qt5ct configuration file.
    pub fn qt5ct_config_file(&self) -> PathBuf {
        self.config_home.join(QT5CT_DIR).join(QT5CT_CONFIG_FILE)
    }

    /// Returns the path of the qt6ct color scheme.
    pub fn qt6ct_scheme_file(&self) -> PathBuf {
        self.qtct_dir(QT6CT_DIR).join(QT_SCHEME_FILE_NAME)
    }

    /// Returns the path of the qt6ct configuration file.
    pub fn qt6ct_config_file(&self) -> PathBuf {
        self.config_home.join(QT6CT_DIR).join(QT6CT_CONFIG_FILE)
    }

    /// Returns the `colors/` directory of a qt5ct/qt6ct configuration.
    fn qtct_dir(&self, tool: &str) -> PathBuf {
        self.config_home.join(tool).join(QT_COLORS_SUBDIR)
    }
}

/// Outcome of one Qt application pass.
///
/// A pass writes several independent files; a failure in one (for example an
/// unwritable qt6ct directory) must not prevent the others from being applied.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct QtApplyReport {
    /// Files whose content changed and were written.
    pub written: Vec<PathBuf>,

    /// Files that could not be written, with the underlying error message.
    pub failures: Vec<QtWriteFailure>,
}

impl QtApplyReport {
    /// Returns whether every file was applied successfully.
    pub fn is_complete(&self) -> bool {
        self.failures.is_empty()
    }
}

/// One configuration file that could not be written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QtWriteFailure {
    /// File that failed to write.
    pub path: PathBuf,

    /// Human-readable cause of the failure.
    pub error: String,
}

/// Writes Qt and KDE color schemes for a resolved theme.
pub struct QtThemeWriter {
    /// Configuration locations to write to.
    paths: QtPaths,
}

impl QtThemeWriter {
    /// Creates a writer for explicit locations.
    pub fn new(paths: QtPaths) -> Self {
        Self { paths }
    }

    /// Creates a writer for the current user's XDG homes.
    ///
    /// # Errors
    /// Returns [`rde_core::errors::RdeError::NotFound`] when the XDG homes
    /// cannot be resolved.
    pub fn resolve() -> RdeResult<Self> {
        Ok(Self::new(QtPaths::resolve()?))
    }

    /// Applies a theme to every Qt and KDE configuration file.
    ///
    /// # Workflow
    /// 1. Render the KDE color scheme and merge it into `kdeglobals`
    /// 2. Render the qt5ct and qt6ct schemes and activate them
    /// 3. Write each file atomically, skipping unchanged content
    /// 4. Report written files and per-file failures
    ///
    /// # Parameters
    /// - `theme`: active theme with its resolved palette
    ///
    /// # Returns
    /// A report describing which files changed and which failed.
    pub fn apply(&self, theme: &Theme) -> QtApplyReport {
        let mut report = QtApplyReport::default();

        for (path, contents) in self.write_plan(theme) {
            match write_atomic_if_changed(&path, &contents) {
                Ok(true) => {
                    debug!(path = %path.display(), "wrote Qt configuration");
                    report.written.push(path);
                }
                Ok(false) => {
                    debug!(path = %path.display(), "Qt configuration already up to date");
                }
                Err(error) => {
                    warn!(
                        path = %path.display(),
                        %error,
                        "failed to write Qt configuration"
                    );
                    report.failures.push(QtWriteFailure {
                        path,
                        error: error.to_string(),
                    });
                }
            }
        }

        info!(
            theme = %theme.manifest.name,
            scheme = %theme.color_scheme,
            written = report.written.len(),
            failures = report.failures.len(),
            "Qt color scheme applied"
        );

        report
    }

    /// Builds every file path and its rendered contents for a theme.
    fn write_plan(&self, theme: &Theme) -> Vec<(PathBuf, String)> {
        let palette = &theme.palette;

        let kde_scheme = kde::render_color_scheme(palette);
        let kde_globals =
            kde::merge_kdeglobals(&read_existing(&self.paths.kde_globals_file()), palette);

        let qt_scheme = qtct::render_scheme(palette);
        let qt5ct_config = qtct::activate_config(
            &read_existing(&self.paths.qt5ct_config_file()),
            &self.paths.qt5ct_scheme_file(),
        );
        let qt6ct_config = qtct::activate_config(
            &read_existing(&self.paths.qt6ct_config_file()),
            &self.paths.qt6ct_scheme_file(),
        );

        vec![
            (self.paths.kde_color_scheme_file(), kde_scheme),
            (self.paths.kde_globals_file(), kde_globals),
            (self.paths.qt5ct_scheme_file(), qt_scheme.clone()),
            (self.paths.qt6ct_scheme_file(), qt_scheme),
            (self.paths.qt5ct_config_file(), qt5ct_config),
            (self.paths.qt6ct_config_file(), qt6ct_config),
        ]
    }
}

/// Applies a theme to the current user's Qt and KDE configuration.
///
/// # Errors
/// Returns [`rde_core::errors::RdeError::NotFound`] when the XDG homes cannot
/// be resolved. Individual write failures are reported in the result so the
/// service can continue running.
pub fn apply(theme: &Theme) -> RdeResult<QtApplyReport> {
    Ok(QtThemeWriter::resolve()?.apply(theme))
}

/// Reads an existing configuration file, treating it as empty when absent.
fn read_existing(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use std::{
        path::PathBuf,
        sync::atomic::{AtomicU64, Ordering},
    };

    use super::*;
    use crate::{
        backend::ThemeBackend,
        domain::theme::{ColorScheme, ThemeId, ThemeManifest},
    };

    /// Isolated XDG homes removed when the test ends.
    struct TempHomes {
        root: PathBuf,
    }

    impl TempHomes {
        fn new(label: &str) -> Self {
            static COUNTER: AtomicU64 = AtomicU64::new(0);

            let unique = COUNTER.fetch_add(1, Ordering::Relaxed);
            let root = std::env::temp_dir().join(format!(
                "rde-theme-qt-{}-{label}-{unique}",
                std::process::id()
            ));
            let _ = fs::remove_dir_all(&root);
            fs::create_dir_all(&root).expect("create temporary homes");

            Self { root }
        }

        fn paths(&self) -> QtPaths {
            QtPaths::from_homes(self.root.join("config"), self.root.join("data"))
        }

        fn writer(&self) -> QtThemeWriter {
            QtThemeWriter::new(self.paths())
        }

        fn read(&self, path: &Path) -> String {
            fs::read_to_string(path).expect("read generated file")
        }
    }

    impl Drop for TempHomes {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.root);
        }
    }

    fn theme(scheme: ColorScheme) -> Theme {
        let manifest = ThemeManifest::new(ThemeId::new("default").expect("valid id"), "#6DD6DA")
            .expect("valid manifest");

        ThemeBackend::resolve(&manifest, scheme).expect("resolve theme")
    }

    #[test]
    fn apply_writes_all_configuration_files() {
        let homes = TempHomes::new("apply");
        let paths = homes.paths();
        let theme = theme(ColorScheme::Dark);

        let report = homes.writer().apply(&theme);

        assert!(report.is_complete(), "every file must be writable");
        assert_eq!(report.written.len(), 6);

        let kde_scheme = homes.read(&paths.kde_color_scheme_file());
        assert!(kde_scheme.contains("ColorScheme=RdeM3"));
        assert!(kde_scheme.contains("[Colors:Window]"));
        assert!(kde_scheme.contains("[WM]"));

        let kde_globals = homes.read(&paths.kde_globals_file());
        assert!(kde_globals.contains("ColorScheme=RdeM3"));
        assert!(kde_globals.contains("[Colors:Selection]"));

        for scheme in [paths.qt5ct_scheme_file(), paths.qt6ct_scheme_file()] {
            let contents = homes.read(&scheme);
            assert!(contents.contains("[ColorScheme]"));
            assert!(contents.contains("active_colors="));
            assert!(contents.contains("disabled_colors="));
        }

        for config in [paths.qt5ct_config_file(), paths.qt6ct_config_file()] {
            let contents = homes.read(&config);
            assert!(contents.contains("[Appearance]"));
            assert!(contents.contains("custom_palette=true"));
            assert!(contents.contains("color_scheme_path="));
        }
    }

    #[test]
    fn apply_is_idempotent() {
        let homes = TempHomes::new("idempotent");
        let writer = homes.writer();
        let theme = theme(ColorScheme::Light);

        assert_eq!(writer.apply(&theme).written.len(), 6);

        let second = writer.apply(&theme);
        assert!(second.is_complete());
        assert!(
            second.written.is_empty(),
            "unchanged configuration must not be rewritten"
        );
    }

    #[test]
    fn apply_preserves_existing_qtct_settings() {
        let homes = TempHomes::new("preserve");
        let paths = homes.paths();
        let config = paths.qt5ct_config_file();
        fs::create_dir_all(config.parent().expect("parent")).expect("create qt5ct directory");
        fs::write(
            &config,
            "[Appearance]\nstyle=Fusion\nicon_theme=Papirus\ncustom_palette=false\n\n[Fonts]\ngeneral=Inter,10\n",
        )
        .expect("seed qt5ct config");

        homes.writer().apply(&theme(ColorScheme::Light));

        let contents = homes.read(&config);
        assert!(contents.contains("style=Fusion"));
        assert!(contents.contains("icon_theme=Papirus"));
        assert!(contents.contains("custom_palette=true"));
        assert!(contents.contains("[Fonts]\ngeneral=Inter,10"));
    }

    #[test]
    fn generated_colors_come_from_the_resolved_palette() {
        let homes = TempHomes::new("colors");
        let paths = homes.paths();
        let theme = theme(ColorScheme::Dark);

        homes.writer().apply(&theme);

        let window_line = format!(
            "BackgroundNormal={},{},{}",
            (theme.palette.surface >> 16) & 0xFF,
            (theme.palette.surface >> 8) & 0xFF,
            theme.palette.surface & 0xFF
        );
        assert!(
            homes.read(&paths.kde_globals_file()).contains(&window_line),
            "kdeglobals must use the active surface color"
        );

        let qt_scheme = homes.read(&paths.qt5ct_scheme_file());
        let window_color = format!(
            "#ff{:02x}{:02x}{:02x}",
            (theme.palette.surface >> 16) & 0xFF,
            (theme.palette.surface >> 8) & 0xFF,
            theme.palette.surface & 0xFF
        );
        assert!(
            qt_scheme.contains(&window_color),
            "qt scheme must contain the surface color"
        );
    }

    #[test]
    fn applying_a_new_scheme_rewrites_the_scheme_files() {
        let homes = TempHomes::new("scheme-change");
        let writer = homes.writer();

        writer.apply(&theme(ColorScheme::Light));
        let report = writer.apply(&theme(ColorScheme::Dark));

        assert!(report.is_complete());
        assert!(
            !report.written.is_empty(),
            "switching schemes must update the files"
        );
    }
}
