//! # GTK CSS Emission
//!
//! Renders a [`Palette`] as GTK `@define-color` declarations for `gtk.css`
//! overrides.

use crate::domain::palette::Palette;

/// Header written above the generated declarations.
const CSS_HEADER: &str = "/* Generated by rde-theme; do not edit. */\n";

/// Renders a palette as a GTK CSS override document.
///
/// # Parameters
/// - `palette`: active theme and scheme colors
///
/// # Returns
/// A CSS document with one `@define-color` declaration per role.
pub fn render_css(palette: &Palette) -> String {
    let mut css = String::from(CSS_HEADER);

    for (role, color) in palette.role_map() {
        css.push_str(&format!("@define-color {role} {color};\n"));
    }

    css
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::backend::{MaterialBackend, ThemeBackend};
    use crate::domain::theme::ColorScheme;

    fn palette() -> Palette {
        MaterialBackend
            .palette("#6DD6DA", ColorScheme::Light)
            .expect("palette generation")
    }

    #[test]
    fn every_role_becomes_a_color_definition() {
        let palette = palette();
        let css = render_css(&palette);
        let declarations = css
            .lines()
            .filter(|line| line.starts_with("@define-color "))
            .count();

        assert_eq!(declarations, palette.role_map().len());
        assert!(css.starts_with("/* Generated by rde-theme; do not edit. */\n"));
        assert!(css.contains(&format!(
            "@define-color surface {};\n",
            role_hex(&palette, "surface")
        )));
        assert!(css.contains("@define-color on_surface "));
    }

    #[test]
    fn declarations_are_stable() {
        assert_eq!(render_css(&palette()), render_css(&palette()));
    }

    /// Returns the `#RRGGBB` value of a role for assertions.
    fn role_hex(palette: &Palette, role: &str) -> String {
        palette
            .role_map()
            .get(role)
            .cloned()
            .expect("requested role must exist")
    }
}
