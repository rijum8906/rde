/// Complete Material 3 color palette for one scheme.
///
/// Every field is a packed opaque ARGB value (`0xFFRRGGBB`) generated by
/// Material Color Utilities. Use [`MaterialColorPalette::role_map`] when a
/// string-keyed representation is more convenient.
///
/// # Fields
/// - `primary`, `on_primary`, `primary_container`, `on_primary_container`:
///   high-emphasis action colors
/// - `secondary`, `on_secondary`, `secondary_container`,
///   `on_secondary_container`: secondary UI colors
/// - `tertiary`, `on_tertiary`, `tertiary_container`, `on_tertiary_container`:
///   tertiary accent colors
/// - `error`, `on_error`, `error_container`, `on_error_container`: destructive
///   action colors
/// - `background`, `on_background`: legacy background roles
/// - `surface`, `surface_dim`, `surface_bright`, `on_surface`,
///   `surface_variant`, `on_surface_variant`: window and panel backgrounds
/// - `surface_container_lowest` .. `surface_container_highest`: elevation tiers
/// - `surface_tint`: brand tint applied to elevated surfaces
/// - `inverse_surface`, `inverse_on_surface`, `inverse_primary`: high-contrast
///   overlays such as snackbars
/// - `outline`, `outline_variant`: borders and dividers
/// - `shadow`, `scrim`: elevation and modal overlays
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MaterialColorPalette {
    /// High-emphasis action color.
    pub primary: u32,
    /// Foreground color on `primary`.
    pub on_primary: u32,
    /// Container fill for featured elements.
    pub primary_container: u32,
    /// Foreground color on `primary_container`.
    pub on_primary_container: u32,

    /// Lower-emphasis UI color.
    pub secondary: u32,
    /// Foreground color on `secondary`.
    pub on_secondary: u32,
    /// Container fill for secondary elements.
    pub secondary_container: u32,
    /// Foreground color on `secondary_container`.
    pub on_secondary_container: u32,

    /// Complementary accent color.
    pub tertiary: u32,
    /// Foreground color on `tertiary`.
    pub on_tertiary: u32,
    /// Container fill for tertiary elements.
    pub tertiary_container: u32,
    /// Foreground color on `tertiary_container`.
    pub on_tertiary_container: u32,

    /// Error and destructive action color.
    pub error: u32,
    /// Foreground color on `error`.
    pub on_error: u32,
    /// Container fill for error banners and dialogs.
    pub error_container: u32,
    /// Foreground color on `error_container`.
    pub on_error_container: u32,

    /// Legacy background color.
    pub background: u32,
    /// Foreground color on `background`.
    pub on_background: u32,

    /// Standard window and panel background.
    pub surface: u32,
    /// Dimmed surface used for large dark areas.
    pub surface_dim: u32,
    /// Brightened surface used for large light areas.
    pub surface_bright: u32,
    /// Primary text and high-emphasis icons on `surface`.
    pub on_surface: u32,
    /// Subtle surface variant behind cards and dividers.
    pub surface_variant: u32,
    /// Medium-emphasis text on `surface_variant`.
    pub on_surface_variant: u32,

    /// Lowest elevation surface container.
    pub surface_container_lowest: u32,
    /// Low elevation surface container.
    pub surface_container_low: u32,
    /// Default surface container (cards, sidebars).
    pub surface_container: u32,
    /// High elevation surface container.
    pub surface_container_high: u32,
    /// Highest elevation surface container (menus, dialogs).
    pub surface_container_highest: u32,
    /// Tint color used on elevated surfaces.
    pub surface_tint: u32,

    /// High-contrast surface for snackbars and toasts.
    pub inverse_surface: u32,
    /// Foreground color on `inverse_surface`.
    pub inverse_on_surface: u32,
    /// Action color used inside `inverse_surface`.
    pub inverse_primary: u32,

    /// Structural borders and dividers.
    pub outline: u32,
    /// Low-contrast border tint.
    pub outline_variant: u32,

    /// Shadow tint for elevation.
    pub shadow: u32,
    /// Modal backdrop overlay.
    pub scrim: u32,
}

impl MaterialColorPalette {
    /// Generates a palette from a hexadecimal source color.
    ///
    /// # Parameters
    /// - `source_color`: seed color in `#RGB`, `RGB`, `#RRGGBB`, or `RRGGBB`
    ///   form
    /// - `color_scheme`: light or dark variant to generate
    ///
    /// # Returns
    /// The complete Material 3 palette for the requested scheme.
    ///
    /// # Errors
    /// Returns [`RdeError::InvalidValue`] when the source color cannot be
    /// parsed.
    ///
    /// [`RdeError::InvalidValue`]: rde_core::errors::RdeError::InvalidValue
    pub fn from_source_color(source_color: &str, color_scheme: ColorScheme) -> RdeResult<Self> {
        let seed = parse_hex_color(source_color)?;

        Ok(MaterialColorPaletteBuilder::new(seed)
            .build(MaterialColorScheme::from_color_scheme(color_scheme)))
    }

    /// Returns every color role keyed by its canonical snake_case name.
    ///
    /// The map is ordered so repeated calls and D-Bus replies are stable, which
    /// makes it straightforward for CLIs, shells, and toolkit writers to
    /// consume the palette without knowing the struct layout.
    ///
    /// # Returns
    /// A map from role name (e.g. `primary_container`) to `#RRGGBB`.
    pub fn role_map(&self) -> BTreeMap<String, String> {
        [
            ("primary", self.primary),
            ("on_primary", self.on_primary),
            ("primary_container", self.primary_container),
            ("on_primary_container", self.on_primary_container),
            ("secondary", self.secondary),
            ("on_secondary", self.on_secondary),
            ("secondary_container", self.secondary_container),
            ("on_secondary_container", self.on_secondary_container),
            ("tertiary", self.tertiary),
            ("on_tertiary", self.on_tertiary),
            ("tertiary_container", self.tertiary_container),
            ("on_tertiary_container", self.on_tertiary_container),
            ("error", self.error),
            ("on_error", self.on_error),
            ("error_container", self.error_container),
            ("on_error_container", self.on_error_container),
            ("background", self.background),
            ("on_background", self.on_background),
            ("surface", self.surface),
            ("surface_dim", self.surface_dim),
            ("surface_bright", self.surface_bright),
            ("on_surface", self.on_surface),
            ("surface_variant", self.surface_variant),
            ("on_surface_variant", self.on_surface_variant),
            ("surface_container_lowest", self.surface_container_lowest),
            ("surface_container_low", self.surface_container_low),
            ("surface_container", self.surface_container),
            ("surface_container_high", self.surface_container_high),
            ("surface_container_highest", self.surface_container_highest),
            ("surface_tint", self.surface_tint),
            ("inverse_surface", self.inverse_surface),
            ("inverse_on_surface", self.inverse_on_surface),
            ("inverse_primary", self.inverse_primary),
            ("outline", self.outline),
            ("outline_variant", self.outline_variant),
            ("shadow", self.shadow),
            ("scrim", self.scrim),
        ]
        .into_iter()
        .map(|(role, color)| (role.to_string(), format_hex_color(color)))
        .collect()
    }
}

impl Default for MaterialColorPalette {
    /// Builds the light palette of the shipped default source color.
    fn default() -> Self {
        MaterialColorPaletteBuilder::new(DEFAULT_THEME_SOURCE_COLOR_ARGB)
            .build(MaterialColorScheme::Light)
    }
}

/// Material 3 scheme variant including its contrast level.
///
/// Each variant maps onto the primitive parameters Material Color Utilities
/// expects: whether the palette is dark and how much extra contrast to apply.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MaterialColorScheme {
    /// Standard light scheme.
    Light,
    /// Light scheme with medium contrast boost.
    LightMediumContrast,
    /// Light scheme with maximum contrast boost.
    LightHighContrast,
    /// Standard dark scheme.
    Dark,
    /// Dark scheme with medium contrast boost.
    DarkMediumContrast,
    /// Dark scheme with maximum contrast boost.
    DarkHighContrast,
}

impl MaterialColorScheme {
    /// Maps the user-facing light/dark preference onto a standard scheme.
    pub const fn from_color_scheme(color_scheme: ColorScheme) -> Self {
        match color_scheme {
            ColorScheme::Light => Self::Light,
            ColorScheme::Dark => Self::Dark,
        }
    }

    /// Returns whether the scheme produces a dark palette.
    pub const fn is_dark(self) -> bool {
        matches!(
            self,
            Self::Dark | Self::DarkMediumContrast | Self::DarkHighContrast
        )
    }

    /// Returns the contrast level passed to Material Color Utilities.
    pub const fn contrast_level(self) -> f64 {
        match self {
            Self::Light | Self::Dark => 0.0,
            Self::LightMediumContrast | Self::DarkMediumContrast => 0.5,
            Self::LightHighContrast | Self::DarkHighContrast => 1.0,
        }
    }
}

/// Builder that expands a seed color into a Material 3 palette.
///
/// The builder owns the tonal palettes Material Color Utilities derives from the
/// seed, so generating a light and a dark palette from the same theme reuses the
/// same source color.
pub struct MaterialColorPaletteBuilder {
    /// Seed color in the HCT color space.
    source_color: Hct,
    /// Material 3 scheme variant controlling hue and chroma mapping.
    variant: Variant,
}

impl MaterialColorPaletteBuilder {
    /// Creates a builder from a packed ARGB seed color.
    ///
    /// # Parameters
    /// - `source_color_argb`: packed ARGB seed; alpha is ignored
    pub fn new(source_color_argb: u32) -> Self {
        Self {
            source_color: Hct::from_int(source_color_argb),
            variant: Variant::TonalSpot,
        }
    }

    /// Selects a different Material 3 scheme variant.
    ///
    /// Defaults to [`Variant::TonalSpot`], the balanced Material You variant.
    pub fn with_variant(mut self, variant: Variant) -> Self {
        self.variant = variant;
        self
    }

    /// Generates the palette for a scheme.
    ///
    /// # Parameters
    /// - `scheme`: light/dark variant and contrast level to generate
    ///
    /// # Returns
    /// The palette with every Material 3 color role populated.
    pub fn build(&self, scheme: MaterialColorScheme) -> MaterialColorPalette {
        // Step 1: Ask Material Color Utilities for a dynamic scheme. The
        // builder derives all tonal palettes from the seed color.
        let dynamic_scheme = DynamicSchemeBuilder::default()
            .source_color_hct(self.source_color.clone())
            .variant(self.variant)
            .is_dark(scheme.is_dark())
            .contrast_level(scheme.contrast_level())
            .build();

        // Step 2: Map every semantic role onto the corresponding M3 role.
        MaterialColorPalette {
            primary: dynamic_scheme.primary(),
            on_primary: dynamic_scheme.on_primary(),
            primary_container: dynamic_scheme.primary_container(),
            on_primary_container: dynamic_scheme.on_primary_container(),
            secondary: dynamic_scheme.secondary(),
            on_secondary: dynamic_scheme.on_secondary(),
            secondary_container: dynamic_scheme.secondary_container(),
            on_secondary_container: dynamic_scheme.on_secondary_container(),
            tertiary: dynamic_scheme.tertiary(),
            on_tertiary: dynamic_scheme.on_tertiary(),
            tertiary_container: dynamic_scheme.tertiary_container(),
            on_tertiary_container: dynamic_scheme.on_tertiary_container(),
            error: dynamic_scheme.error(),
            on_error: dynamic_scheme.on_error(),
            error_container: dynamic_scheme.error_container(),
            on_error_container: dynamic_scheme.on_error_container(),
            background: dynamic_scheme.background(),
            on_background: dynamic_scheme.on_background(),
            surface: dynamic_scheme.surface(),
            surface_dim: dynamic_scheme.surface_dim(),
            surface_bright: dynamic_scheme.surface_bright(),
            on_surface: dynamic_scheme.on_surface(),
            surface_variant: dynamic_scheme.surface_variant(),
            on_surface_variant: dynamic_scheme.on_surface_variant(),
            surface_container_lowest: dynamic_scheme.surface_container_lowest(),
            surface_container_low: dynamic_scheme.surface_container_low(),
            surface_container: dynamic_scheme.surface_container(),
            surface_container_high: dynamic_scheme.surface_container_high(),
            surface_container_highest: dynamic_scheme.surface_container_highest(),
            surface_tint: dynamic_scheme.surface_tint(),
            inverse_surface: dynamic_scheme.inverse_surface(),
            inverse_on_surface: dynamic_scheme.inverse_on_surface(),
            inverse_primary: dynamic_scheme.inverse_primary(),
            outline: dynamic_scheme.outline(),
            outline_variant: dynamic_scheme.outline_variant(),
            shadow: dynamic_scheme.shadow(),
            scrim: dynamic_scheme.scrim(),
        }
    }
}

impl Default for MaterialColorPaletteBuilder {
    /// Creates a builder seeded with the shipped default source color.
    fn default() -> Self {
        Self::new(DEFAULT_THEME_SOURCE_COLOR_ARGB)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn palette_contains_every_role() {
        let palette = MaterialColorPalette::from_source_color("#6DD6DA", ColorScheme::Light)
            .expect("palette generation");

        let roles = palette.role_map();
        assert_eq!(roles.len(), 37);
        assert_eq!(
            roles.get("primary"),
            Some(&format_hex_color(palette.primary))
        );
        assert_eq!(
            roles.get("surface_container_highest"),
            Some(&format_hex_color(palette.surface_container_highest))
        );
        assert!(roles.contains_key("on_surface"));
    }

    #[test]
    fn light_and_dark_schemes_differ() {
        let light = MaterialColorPalette::from_source_color("#6DD6DA", ColorScheme::Light)
            .expect("light palette");
        let dark = MaterialColorPalette::from_source_color("#6DD6DA", ColorScheme::Dark)
            .expect("dark palette");

        assert_ne!(light.surface, dark.surface);
        assert_ne!(light.on_surface, dark.on_surface);
    }

    #[test]
    fn palette_tracks_the_source_color() {
        let teal = MaterialColorPalette::from_source_color("#006A6A", ColorScheme::Light)
            .expect("teal palette");
        let orange = MaterialColorPalette::from_source_color("#FF6200", ColorScheme::Light)
            .expect("orange palette");

        assert_ne!(teal.primary, orange.primary);
    }

    #[test]
    fn contrast_levels_are_ordered() {
        assert!(!MaterialColorScheme::Light.is_dark());
        assert!(MaterialColorScheme::DarkHighContrast.is_dark());
        assert_eq!(MaterialColorScheme::Light.contrast_level(), 0.0);
        assert_eq!(MaterialColorScheme::DarkHighContrast.contrast_level(), 1.0);
    }

    #[test]
    fn default_palette_uses_the_shipped_seed() {
        let palette = MaterialColorPalette::default();
        let expected = MaterialColorPalette::from_source_color(
            crate::constants::DEFAULT_THEME_SOURCE_COLOR,
            ColorScheme::Light,
        )
        .expect("default palette");

        assert_eq!(palette, expected);
    }
}
