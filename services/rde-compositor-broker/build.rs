use heck::{ToSnakeCase, ToUpperCamelCase};
use quick_xml::Reader;
use quick_xml::events::Event;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

#[derive(Default)]
struct Arg {
    name: String,
    ty: String,
}

#[derive(Default)]
struct Member {
    name: String,
    args: Vec<Arg>,
}

fn main() {
    println!("cargo:rerun-if-changed=metadata");
    let out = std::env::var("OUT_DIR").unwrap();
    let out = Path::new(&out).join("wayfire_ipc.rs");

    // interface -> (methods, events)
    let mut methods: BTreeMap<String, Member> = BTreeMap::new();
    let mut events: BTreeMap<String, Member> = BTreeMap::new();

    for entry in fs::read_dir("metadata").expect("metadata/ dir") {
        let path = entry.unwrap().path();
        if path.extension().and_then(|s| s.to_str()) != Some("xml") {
            continue;
        }
        parse_file(&path, &mut methods, &mut events);
    }

    let mut code = String::new();
    writeln!(code, "// AUTO-GENERATED by build.rs — do not edit").unwrap();
    writeln!(code, "use serde::{{Deserialize, Serialize}};").unwrap();

    // ---- per-member data structs ----
    for (kind, map) in [("req", &methods), ("ev", &events)] {
        for (full, m) in map {
            let struct_name = struct_ident(kind, full);
            writeln!(
                code,
                "\n#[derive(Debug, Clone, Serialize, Deserialize, Default)]"
            )
            .unwrap();
            writeln!(code, "pub struct {struct_name} {{").unwrap();
            for a in &m.args {
                let f = a.name.to_snake_case();
                let t = rust_type(&a.ty);
                writeln!(code, "    #[serde(rename = \"{}\", default)]", a.name).unwrap();
                writeln!(code, "    pub {f}: {t},").unwrap();
            }
            writeln!(code, "}}").unwrap();
        }
    }

    // ---- Request enum (tag = "method") ----
    writeln!(code, "\n#[derive(Debug, Clone, Serialize, Deserialize)]").unwrap();
    writeln!(code, "#[serde(tag = \"method\", content = \"data\")]").unwrap();
    writeln!(code, "pub enum Request {{").unwrap();
    methods.iter().for_each(|(full, _)| {
        let variant = variant_ident(full);
        let payload = struct_ident("req", full);
        writeln!(code, "    #[serde(rename = \"{full}\")]").unwrap();
        writeln!(code, "    {variant}({payload}),").unwrap();
    });
    writeln!(code, "}}").unwrap();

    // ---- Event enum (tag = "event") ----
    writeln!(code, "\n#[derive(Debug, Clone, Serialize, Deserialize)]").unwrap();
    writeln!(code, "#[serde(tag = \"event\", content = \"data\")]").unwrap();
    writeln!(code, "pub enum Event {{").unwrap();
    events.iter().for_each(|(full, _)| {
        let variant = variant_ident(full);
        let payload = struct_ident("ev", full);
        writeln!(code, "    #[serde(rename = \"{full}\")]").unwrap();
        writeln!(code, "    {variant}({payload}),").unwrap();
    });
    writeln!(code, "    #[serde(other)]").unwrap();
    writeln!(code, "    Unknown,").unwrap(); // forward-compat
    writeln!(code, "}}").unwrap();

    fs::write(out, code).unwrap();
}

fn parse_file(
    path: &Path,
    methods: &mut BTreeMap<String, Member>,
    events: &mut BTreeMap<String, Member>,
) {
    let mut reader = Reader::from_file(path).unwrap();
    let mut buf = Vec::new();
    let mut iface = String::new();
    let mut cur: Option<(bool, Member)> = None; // (is_event, member)

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) => match e.name().as_ref() {
                "interface" => {
                    iface = attr(&e, "name").unwrap_or_default();
                }
                "method" => {
                    let n = attr(&e, "name").unwrap_or_default();
                    cur = Some((
                        false,
                        Member {
                            name: n,
                            args: vec![],
                        },
                    ));
                }
                "event" => {
                    let n = attr(&e, "name").unwrap_or_default();
                    cur = Some((
                        true,
                        Member {
                            name: n,
                            args: vec![],
                        },
                    ));
                }
                "arg" => {
                    if let Some((_, m)) = cur.as_mut() {
                        m.args.push(Arg {
                            name: attr(&e, "name").unwrap_or_else(|| "arg".into()),
                            ty: attr(&e, "type").unwrap_or_else(|| "unknown".into()),
                        });
                    }
                }
                _ => {}
            },
            Ok(Event::End(e)) => {
                if matches!(e.name().as_ref(), "method" | "event") {
                    if let Some((is_event, m)) = cur.take() {
                        let full = format!("{iface}/{}", m.name);
                        if is_event {
                            events.insert(full, m);
                        } else {
                            methods.insert(full, m);
                        }
                    }
                }
            }
            Ok(Event::Eof) => break,
            Err(e) => panic!("{}: {e}", path.display()),
            _ => {}
        }
        buf.clear();
    }
}

fn attr(e: &quick_xml::events::BytesStart, key: &str) -> Option<String> {
    e.attributes()
        .flatten()
        .find(|a| a.key.as_ref() == key)
        .and_then(|a| a.unescape_value().ok().map(|v| v.into_owned()))
}

fn rust_type(ty: &str) -> &'static str {
    match ty {
        "int" | "uint" => "i64",
        "bool" | "boolean" => "bool",
        "string" => "String",
        "double" | "float" => "f64",
        "array" | "list" => "Vec<serde_json::Value>",
        "object" => "serde_json::Value",
        _ => "serde_json::Value", // safe fallback, never fails to compile
    }
}

fn struct_ident(kind: &str, full: &str) -> String {
    format!(
        "{}{}",
        kind.to_upper_camel_case(),
        full.to_upper_camel_case()
    )
}
fn variant_ident(full: &str) -> String {
    full.to_upper_camel_case()
}
